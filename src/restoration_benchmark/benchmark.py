"""Select on calibration images, freeze parameters, evaluate held-out images."""

import argparse
import csv
import importlib.metadata
import json
from pathlib import Path
import platform
import time

import numpy as np

from .data import make_cases, manifest
from .methods import CANDIDATES, restore
from .metrics import psnr, score


def select_parameters(calibration_cases):
    if not calibration_cases or any(c.split != "calibration" for c in calibration_cases):
        raise ValueError("Parameter selection requires calibration cases only.")
    selected, search = {"noisy_input": {}}, []
    for method, candidates in CANDIDATES.items():
        trials = []
        for parameters in candidates:
            mean_psnr = float(np.mean([
                psnr(c.reference, restore(c.noisy, method, parameters))
                for c in calibration_cases
            ]))
            trial = {"method": method, "parameters": parameters, "calibration_psnr_db": mean_psnr}
            search.append(trial)
            trials.append(trial)
        # Stable ties resolve to the first declared candidate. No test images are inspected.
        selected[method] = max(trials, key=lambda t: t["calibration_psnr_db"])["parameters"].copy()
    return selected, search


def evaluate(test_cases, selected):
    if not test_cases or any(c.split != "test" for c in test_cases):
        raise ValueError("Evaluation requires test cases only.")
    rows, times = [], {method: [] for method in selected}
    for c in test_cases:
        for method, parameters in selected.items():
            estimate = restore(c.noisy, method, parameters)
            measurements = []
            for _ in range(3):
                start = time.perf_counter_ns()
                restore(c.noisy, method, parameters)
                measurements.append((time.perf_counter_ns() - start) / 1e6)
            times[method].append(float(np.median(measurements)))
            rows.append({"case_id": c.case_id, "group": c.group, "family": c.family,
                         "sigma": c.sigma, "method": method, **score(c.reference, estimate)})
    return rows, times


def paired_interval(rows, method, repetitions=2000):
    """Resample clean-image groups so two noise levels of one image stay together."""
    baseline = {r["case_id"]: r["psnr_db"] for r in rows if r["method"] == "noisy_input"}
    by_group = {}
    for row in rows:
        if row["method"] == method:
            by_group.setdefault(row["group"], []).append(row["psnr_db"] - baseline[row["case_id"]])
    deltas = np.array([np.mean(by_group[key]) for key in sorted(by_group)])
    rng = np.random.default_rng(0)
    samples = rng.choice(deltas, size=(repetitions, len(deltas)), replace=True).mean(axis=1)
    return [float(v) for v in np.quantile(samples, [0.05, 0.95])]


def summarize(rows, selected):
    result = {}
    for method in selected:
        matches = [r for r in rows if r["method"] == method]
        result[method] = {
            "parameters": selected[method], "n_test_cases": len(matches),
            **{key: float(np.mean([r[key] for r in matches]))
               for key in ("psnr_db", "ssim", "edge_mae")},
            "delta_psnr_90pct_interval": paired_interval(rows, method),
        }
    return result


def comparison_panel(test_cases, selected, destination):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    cases = [next(c for c in test_cases if c.family == family and c.sigma == 0.10)
             for family in ("particles", "lines")]
    columns = ["reference", *selected]
    fig, axes = plt.subplots(2, len(columns), figsize=(12.5, 5.3), constrained_layout=True)
    for i, case in enumerate(cases):
        for j, method in enumerate(columns):
            image = case.reference if method == "reference" else restore(case.noisy, method, selected[method])
            axes[i, j].imshow(image, cmap="gray", vmin=0, vmax=1, interpolation="nearest")
            label = "Clean reference" if method == "reference" else method.replace("_", " ").title()
            axes[i, j].set_title(label, fontsize=10)
            axes[i, j].set_xticks([])
            axes[i, j].set_yticks([])
            if j == 0:
                axes[i, j].set_ylabel(case.family.title(), fontsize=11)
    fig.suptitle("Synthetic phantoms · held-out seed 100 · Gaussian noise before clipping, σ = 0.10", fontsize=12)
    fig.savefig(destination, dpi=160)
    plt.close(fig)


def write_report(destination, summary, rows):
    lines = ["# Held-out denoising results", "",
             "Generated by `python -m restoration_benchmark`. Synthetic images only.", "",
             "12 calibration cases (6 clean images) select one setting per method. "
             "32 test cases (16 different clean images, two noise levels) are scored afterwards.", "",
             "| Method | Frozen setting | Mean PSNR (dB) ↑ | Mean SSIM ↑ | Edge MAE ↓ | 90% interval for ΔPSNR vs noisy input |",
             "|---|---|---:|---:|---:|---|" ]
    for method, item in summary.items():
        low, high = item["delta_psnr_90pct_interval"]
        lines.append(f"| {method} | `{json.dumps(item['parameters'], sort_keys=True)}` | "
                     f"{item['psnr_db']:.3f} | {item['ssim']:.4f} | {item['edge_mae']:.5f} | [{low:.3f}, {high:.3f}] dB |")
    lines += ["", "## By pattern family", "",
              "| Family | Method | PSNR (dB) | SSIM | Edge MAE |", "|---|---|---:|---:|---:|"]
    for family in ("particles", "lines"):
        for method in summary:
            subset = [r for r in rows if r["method"] == method and r["family"] == family]
            means = [np.mean([r[key] for r in subset]) for key in ("psnr_db", "ssim", "edge_mae")]
            lines.append(f"| {family} | {method} | {means[0]:.3f} | {means[1]:.4f} | {means[2]:.5f} |")
    lines += ["", "## Interpretation and limits", "",
              "A higher average PSNR does not establish preservation of small features. "
              "Inspect the line patterns, SSIM and edge error alongside the aggregate score.", "",
              "Intervals resample the 16 clean-image groups, keeping their two noise levels together. "
              "They describe sampling variation within this generator, not performance on real microscopy.", "",
              "Images are scored on [0,1] with the same five-pixel border excluded. "
              "SSIM uses an 11×11 Gaussian window (σ=1.5) and population covariance. "
              "Noise is added before clipping and 16-bit quantization. "
              "Its requested σ is not the variance of the clipped residual.", "",
              "`timing.json` contains local measurements only: each entry is a median of three "
              "warm calls, excluding metrics and plotting. It is regenerated, not committed, "
              "and is not a cross-hardware speed claim.", "",
              "![Fixed-scale comparison of synthetic images](comparison.png)", ""]
    destination.write_text("\n".join(lines))


def run(output, verify_manifest=None):
    calibration, test = make_cases("calibration"), make_cases("test")
    if {c.group for c in calibration} & {c.group for c in test}:
        raise ValueError("Calibration/test image groups overlap.")
    source_manifest = manifest(calibration + test)
    if verify_manifest is not None:
        if json.loads(Path(verify_manifest).read_text()) != source_manifest:
            raise ValueError("Input manifest mismatch; no benchmark outputs were written.")
    selected, search = select_parameters(calibration)
    rows, times = evaluate(test, selected)
    summary = summarize(rows, selected)
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    def write_json(name, value):
        (output / name).write_text(json.dumps(value, indent=2, sort_keys=True, allow_nan=False) + "\n")
    write_json("input_manifest.json", source_manifest)
    write_json("selected_parameters.json", {"selected": selected, "calibration_search": search})
    write_json("summary.json", summary)
    write_json("timing.json", {method: {"p50_ms": float(np.median(v)),
                                       "p95_ms": float(np.quantile(v, 0.95))}
                               for method, v in times.items()})
    write_json("environment.json", {"python": platform.python_version(), "platform": platform.platform(),
                                   "packages": {p: importlib.metadata.version(p)
                                                for p in ("numpy", "scipy", "matplotlib")}})
    with (output / "per_case.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    comparison_panel(test, selected, output / "comparison.png")
    write_report(output / "results.md", summary, rows)
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="reports")
    parser.add_argument("--verify-manifest", help="Compare regenerated inputs with a committed manifest before scoring.")
    args = parser.parse_args()
    summary = run(args.output, args.verify_manifest)
    print(json.dumps(summary, indent=2))
